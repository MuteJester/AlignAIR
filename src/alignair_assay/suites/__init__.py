"""The suite registry: every suite the assay can build, by name.

A suite is one module in ``catalog/`` defining ``Suite`` objects (``base``); it is generated by ``engine``. To add
one, write its module, list its suites in ``_CATALOG`` and the module in ``_MODULES`` (its source is part of the
suite's build identity, ``catalog_module``).
"""
from __future__ import annotations

from types import ModuleType

from alignair_assay.suites.base import Suite
from alignair_assay.suites.catalog import (
    s00_toy,
    s01_core,
    s02_siblings,
    s03_junction,
    s04_truncation,
    s05_indels,
    s06_d_observability,
    s07_novel,
    s08_genotype,
    s09_clonal,
    s10_heldout,
    s11_orientation,
    s12_noise,
    s13_flanks,
)

_CATALOG = (s00_toy.S0, s00_toy.S0_EXHAUST, s00_toy.S0_COHORT, s01_core.S1, s02_siblings.S2, s03_junction.S3,
            s04_truncation.S4, s05_indels.S5, s06_d_observability.S6, s07_novel.S7, s08_genotype.S8, s09_clonal.S9,
            s10_heldout.S10, s11_orientation.S11, s12_noise.S12, s13_flanks.S13)
_MODULES = (s00_toy, s01_core, s02_siblings, s03_junction, s04_truncation, s05_indels, s06_d_observability, s07_novel,
            s08_genotype, s09_clonal, s10_heldout, s11_orientation, s12_noise, s13_flanks)


def _registry(suites: tuple[Suite, ...]) -> dict[str, Suite]:
    registry: dict[str, Suite] = {}
    for suite in suites:
        if suite.name in registry:
            raise ValueError(f"suite {suite.name} is registered twice")
        registry[suite.name] = suite
    return registry


SUITES: dict[str, Suite] = _registry(_CATALOG)


def get_suite(name: str) -> Suite:
    """The registered suite ``name``; ValueError listing the known names otherwise."""
    try:
        return SUITES[name]
    except KeyError:
        raise ValueError(f"unknown suite {name!r}; known suites: {', '.join(SUITES)}") from None


def catalog_module(name: str) -> ModuleType:
    """The ``catalog/`` module defining the registered suite ``name`` (a module-level ``Suite`` of that name), whose
    source the suite's build depends on. ValueError for an unknown suite or one no catalog module defines."""
    get_suite(name)
    for module in _MODULES:
        if any(isinstance(value, Suite) and value.name == name for value in vars(module).values()):
            return module
    raise ValueError(f"suite {name} is registered but defined in no catalog module; list its module in _MODULES")
