"""The suite registry: every suite the assay can build, by name.

A suite is one module in ``catalog/`` defining ``Suite`` objects (``base``); it is generated by ``engine``. To add
one, write its module and list its suites in ``_CATALOG``.
"""
from __future__ import annotations

from alignair_assay.suites.base import Suite
from alignair_assay.suites.catalog import (
    s00_toy,
    s01_core,
    s02_siblings,
    s03_junction,
    s04_truncation,
    s05_indels,
    s06_d_observability,
    s09_clonal,
    s10_heldout,
    s11_orientation,
    s12_noise,
)

_CATALOG = (s00_toy.S0, s00_toy.S0_EXHAUST, s00_toy.S0_COHORT, s01_core.S1, s02_siblings.S2, s03_junction.S3,
            s04_truncation.S4, s05_indels.S5, s06_d_observability.S6, s09_clonal.S9, s10_heldout.S10,
            s11_orientation.S11, s12_noise.S12)


def _registry(suites: tuple[Suite, ...]) -> dict[str, Suite]:
    registry: dict[str, Suite] = {}
    for suite in suites:
        if suite.name in registry:
            raise ValueError(f"suite {suite.name} is registered twice")
        registry[suite.name] = suite
    return registry


SUITES: dict[str, Suite] = _registry(_CATALOG)


def get_suite(name: str) -> Suite:
    """The registered suite ``name``; ValueError listing the known names otherwise."""
    try:
        return SUITES[name]
    except KeyError:
        raise ValueError(f"unknown suite {name!r}; known suites: {', '.join(SUITES)}") from None
